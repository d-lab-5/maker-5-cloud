// Generate amplify/functions/graph-shared/ontology.generated.ts from
// packages/ontology, the source of truth (ADR-0007). Amplify's backend build
// installs backend/ only, so the Lambdas cannot read the workspace package at
// build time; they carry this generated copy. graph-shared/validate.test.ts
// fails when it drifts.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, "../../packages/ontology");
const files = {
  TBOX: "tbox/maker-5.ttl",
  CONCEPTS: "tbox/maker-5-concepts.ttl",
  SHAPES: "shapes/maker-5-shapes.ttl",
};
let out = "// GENERATED by backend/scripts/sync-ontology.mjs from packages/ontology. Do not edit.\n";
for (const [name, rel] of Object.entries(files)) {
  out += `export const ${name} = ${JSON.stringify(fs.readFileSync(path.join(src, rel), "utf8"))};\n`;
}
const dest = path.resolve(here, "../amplify/functions/graph-shared/ontology.generated.ts");
fs.writeFileSync(dest, out);
console.log(`  wrote ${path.relative(process.cwd(), dest)}`);

// ADR-0019: the article categories, two levels, from the concepts' SKOS. The
// Lambdas (materials-shared) and the site (packages/core) both carry this
// list, so a value the one accepts the other can show.
import N3 from "n3";
const SKOS = "http://www.w3.org/2004/02/skos/core#";
const store = new N3.Store(new N3.Parser().parse(fs.readFileSync(path.join(src, files.CONCEPTS), "utf8")));
const scheme = "https://maker-5.cloud/ontology#ArticleCategories";
const one = (s, p) => store.getObjects(s, SKOS + p, null)[0];
const cats = store.getSubjects(SKOS + "inScheme", scheme, null).map((c) => {
  const label = Object.fromEntries(store.getObjects(c, SKOS + "prefLabel", null).map((l) => [l.language, l.value]));
  const broader = one(c, "broader");
  return { code: one(c, "notation").value, top: broader ? one(broader, "notation").value : null, label };
});
// the file's order: each top category, then its subcategories
const tops = cats.filter((c) => !c.top);
cats.splice(0, cats.length, ...tops.flatMap((t) => [t, ...cats.filter((c) => c.top === t.code)]));
const catTs = "// GENERATED by backend/scripts/sync-ontology.mjs from packages/ontology (m5:ArticleCategories). Do not edit.\n" +
  "export interface Category { code: string; top: string | null; label: Record<string, string> }\n" +
  `export const CATEGORY_LIST: Category[] = ${JSON.stringify(cats, null, 1)};\n`;
for (const rel of ["../amplify/functions/materials-shared/categories.generated.ts", "../../packages/core/src/categories.generated.ts"]) {
  const d = path.resolve(here, rel);
  fs.writeFileSync(d, catTs);
  console.log(`  wrote ${path.relative(process.cwd(), d)}`);
}
